// BILINGUAL LANGUAGE SWITCHER
// ==========================================================================
function initLanguage() {
  const btnEs = document.getElementById("lang-es");
  const btnEn = document.getElementById("lang-en");
  const btnPt = document.getElementById("lang-pt");
  const btnDe = document.getElementById("lang-de");
  
  if (btnEs) btnEs.addEventListener("click", () => switchLanguage("es"));
  if (btnEn) btnEn.addEventListener("click", () => switchLanguage("en"));
  if (btnPt) btnPt.addEventListener("click", () => switchLanguage("pt"));
  if (btnDe) btnDe.addEventListener("click", () => switchLanguage("de"));
}

function switchLanguage(lang) {
  currentLang = lang;
  
  // Toggle Active States para todos los idiomas soportados
  const langs = ["es", "en", "pt", "de"];
  langs.forEach(l => {
    const btn = document.getElementById(`lang-${l}`);
    if (btn) {
      btn.classList.toggle("active", l === lang);
    }
  });
  
  // Translate all DOM elements with data-i18n attribute
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang] && translations[lang][key]) {
      // Check if translating placeholders
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        if (key.startsWith("ph-")) {
          el.setAttribute("placeholder", translations[lang][key]);
        }
      } else {
        el.innerHTML = translations[lang][key];
      }
    }
  });
  
  // Recalculate price in the new language
  calculatePrice();
}

