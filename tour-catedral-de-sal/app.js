function initCalculator() {
  const btnMinus = document.getElementById("btn-minus");
  const btnPlus = document.getElementById("btn-plus");
  const countEl = document.getElementById("calc-travelers-count");
  
  if (btnMinus && btnPlus && countEl) {
    btnMinus.addEventListener("click", () => {
      if (travelersCount > 1) {
        travelersCount--;
        countEl.innerText = travelersCount;
        calculatePrice();
      }
    });
    
    btnPlus.addEventListener("click", () => {
      if (travelersCount < 50) {
        travelersCount++;
        countEl.innerText = travelersCount;
        calculatePrice();
      }
    });
  }

  // Service Type Selection
  const optShared = document.getElementById("opt-shared");
  const optPrivate = document.getElementById("opt-private");
  
  if (optShared && optPrivate) {
    optShared.addEventListener("click", () => {
      serviceType = "shared";
      optShared.classList.add("selected");
      optPrivate.classList.remove("selected");
      calculatePrice();
    });
    optPrivate.addEventListener("click", () => {
      serviceType = "private";
      optPrivate.classList.add("selected");
      optShared.classList.remove("selected");
      calculatePrice();
    });
  }

  // Lunch Selection
  const optLunchYes = document.getElementById("opt-lunch-yes");
  const optLunchNo = document.getElementById("opt-lunch-no");
  
  if (optLunchYes && optLunchNo) {
    optLunchYes.addEventListener("click", () => {
      hasLunch = true;
      optLunchYes.classList.add("selected");
      optLunchNo.classList.remove("selected");
      calculatePrice();
    });
    optLunchNo.addEventListener("click", () => {
      hasLunch = false;
      optLunchNo.classList.add("selected");
      optLunchYes.classList.remove("selected");
      calculatePrice();
    });
  }
}

function calculatePrice() {
  let basePricePerPerson = 99;
  let discountPercent = 0;
  
  if (serviceType === "shared") {
    basePricePerPerson = hasLunch ? 99 : 84;
    // Apply 5% discount starting from 5 travelers
    if (travelersCount >= 5) {
      discountPercent = 5;
    }
  } else {
    // Private tour pricing scales dynamically
    if (travelersCount === 1) {
      basePricePerPerson = 220;
    } else if (travelersCount === 2) {
      basePricePerPerson = 140;
    } else if (travelersCount === 3) {
      basePricePerPerson = 110;
    } else if (travelersCount >= 4 && travelersCount <= 5) {
      basePricePerPerson = 90;
    } else {
      basePricePerPerson = 80;
    }
    
    // Deduct $15 USD per person if lunch is excluded
    if (!hasLunch) {
      basePricePerPerson -= 15;
    }
  }
  
  const finalPricePerPerson = Math.round(basePricePerPerson * (1 - (discountPercent / 100)));
  const finalTotalPrice = finalPricePerPerson * travelersCount;
  
  const copRate = 4000;
  const copPerPersonStr = (finalPricePerPerson * copRate).toLocaleString('es-CO');
  const copTotalStr = (finalTotalPrice * copRate).toLocaleString('es-CO');

  // Update Price display in DOM
  const valEl = document.getElementById("price-value");
  if (valEl) {
    valEl.innerText = `$${finalPricePerPerson} USD (~ $${copPerPersonStr} COP)`;
  }
  
  const totalValEl = document.getElementById("total-price-value");
  if (totalValEl) {
    totalValEl.innerText = `$${finalTotalPrice} USD (~ $${copTotalStr} COP)`;
  }
  
  // Update price-tag indicators on option cards
  const priceTagShared = document.getElementById("price-tag-shared");
  const priceTagPrivate = document.getElementById("price-tag-private");
  if (priceTagShared && priceTagPrivate) {
    // Shared base price tag
    let sharedBase = hasLunch ? 99 : 84;
    priceTagShared.innerText = `$${sharedBase} USD`;
    
    // Private base price tag for current travelers count
    let privateBase = 140; // Default or traveler-specific
    if (travelersCount === 1) privateBase = 220;
    else if (travelersCount === 2) privateBase = 140;
    else if (travelersCount === 3) privateBase = 110;
    else if (travelersCount >= 4 && travelersCount <= 5) privateBase = 90;
    else privateBase = 80;
    
    if (!hasLunch) privateBase -= 15;
    priceTagPrivate.innerText = `$${privateBase} USD`;
  }
  
  // Update savings message
  const savingEl = document.getElementById("calc-saving-info");
  if (savingEl) {
    if (discountPercent > 0) {
      let savingTxt = translations[currentLang]["calc-saving"];
      savingTxt = savingTxt.replace("{percent}", discountPercent);
      savingEl.innerHTML = `<i class="fa-solid fa-tags"></i> ${savingTxt}`;
      savingEl.style.display = "block";
    } else if (serviceType === "private") {
      savingEl.innerHTML = `<i class="fa-solid fa-circle-info"></i> ${currentLang === "es" ? "Tarifa privada optimizada por volumen de grupo." : "Private rate optimized by group volume."}`;
      savingEl.style.display = "block";
    } else {
      savingEl.innerHTML = `<i class="fa-solid fa-circle-info"></i> ${translations[currentLang]["calc-no-saving"]}`;
      savingEl.style.display = "block";
    }
  }
}

