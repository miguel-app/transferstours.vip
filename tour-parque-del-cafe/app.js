// ==========================================================================
function initCalculator() {
  const btnMinus = document.getElementById("btn-minus");
  const btnPlus = document.getElementById("btn-plus");
  const countEl = document.getElementById("calc-travelers-count");
  
  if (btnMinus && btnPlus && countEl) {
    btnMinus.addEventListener("click", () => {
      if (travelersCount > 1) {
        travelersCount--;
        countEl.innerText = travelersCount;
        calculatePrice();
      }
    });
    
    btnPlus.addEventListener("click", () => {
      if (travelersCount < 50) {
        travelersCount++;
        countEl.innerText = travelersCount;
        calculatePrice();
      }
    });
  }
}

function calculatePrice() {
  let basePricePerPerson = 66; // Tarifa estándar $66 USD (de $220.000 COP + 20% margen)
  let discountPercent = 0;
  const savingEl = document.getElementById("calc-saving-info");
  const bookBtn = document.getElementById("calc-book-btn");
  
  // Condicionales de tarifa según pax
  if (travelersCount < 2) {
    // Menos de 2 viajeros - Alerta de mínimo
    if (savingEl) {
      savingEl.innerHTML = translations[currentLang]["calc-min-warning"] || translations["es"]["calc-min-warning"];
      savingEl.style.display = "block";
      savingEl.style.backgroundColor = "rgba(231, 76, 60, 0.1)";
      savingEl.style.borderColor = "var(--color-danger)";
      savingEl.style.color = "var(--color-danger)";
    }
    // Deshabilitar botón
    if (bookBtn) {
      bookBtn.style.opacity = "0.6";
      bookBtn.style.cursor = "not-allowed";
    }
    
    updateDOMPrices(66, 66);
    return;
  }
  
  // Habilitar botón para travelers >= 2
  if (bookBtn) {
    bookBtn.style.opacity = "1";
    bookBtn.style.cursor = "pointer";
  }
  
  if (travelersCount >= 5) {
    basePricePerPerson = 60; // Tarifa grupal $60 USD (de $200.000 COP + 20% margen)
    discountPercent = 9; // ~9% de ahorro respecto a 66 USD
  }
  
  const finalPricePerPerson = basePricePerPerson;
  const finalTotalPrice = finalPricePerPerson * travelersCount;
  
  updateDOMPrices(finalPricePerPerson, finalTotalPrice);
  
  // Actualizar mensaje de ahorro
  if (savingEl) {
    savingEl.style.backgroundColor = "rgba(255, 255, 255, 0.1)";
    savingEl.style.borderColor = "rgba(255, 255, 255, 0.3)";
    savingEl.style.color = "var(--color-white)";
    if (discountPercent > 0) {
      let savingTxt = translations[currentLang]["calc-saving"];
      savingTxt = savingTxt.replace("{percent}", discountPercent);
      savingEl.innerHTML = `<i class="fa-solid fa-tags"></i> ${savingTxt}`;
      savingEl.style.display = "block";
    } else {
      savingEl.innerHTML = `<i class="fa-solid fa-circle-info"></i> ${translations[currentLang]["calc-no-saving"]}`;
      savingEl.style.display = "block";
    }
  }
}

function updateDOMPrices(perPerson, total) {
  const valEl = document.getElementById("price-value");
  if (valEl) {
    valEl.innerText = `$${perPerson} USD`;
  }
  
  const totalValEl = document.getElementById("total-price-value");
  if (totalValEl) {
    totalValEl.innerText = `$${total} USD`;
  }
}

